#!/usr/bin/env python3
"""Independent generator of intent-hash vectors (PRD 3.4). Uses only hashlib + int.to_bytes.
Does NOT call the JS implementation. Writes docs/vectors/intent_hash.json."""
import hashlib, json, os

U64 = 2**64 - 1
U128 = 2**128 - 1
PREFIX = b"amanat/v1"


def intent_hash(mandate_id, recipient, amount, nonce, expires_at_ms):
    r = recipient.encode("utf-8")
    buf = (PREFIX + mandate_id.to_bytes(8, "little") + len(r).to_bytes(4, "little") + r
           + amount.to_bytes(16, "little") + nonce.to_bytes(8, "little")
           + expires_at_ms.to_bytes(8, "little"))
    return hashlib.sha256(buf).hexdigest()


def pos(name, mid, rec, amt, nonce, exp):
    return {
        "name": name,
        "input": {"mandateId": str(mid), "recipient": rec, "amount": str(amt),
                  "nonce": str(nonce), "expiresAtMs": str(exp)},
        "hash": intent_hash(mid, rec, amt, nonce, exp),
    }


def neg(name, error, **over):
    inp = {"mandateId": "1", "recipient": "shop.testnet", "amount": "1000000",
           "nonce": "1", "expiresAtMs": "1700000000000"}
    inp.update(over)
    return {"name": name, "input": inp, "error": error}


positive = [
    pos("typical", 7, "merchant.testnet", 2_500_000, 42, 1_790_000_000_000),
    pos("all_zero_values", 0, "a", 0, 0, 0),
    pos("max_u64_fields", U64, "shop.testnet", 1, U64, U64),
    pos("max_u128_amount", 1, "shop.testnet", U128, 1, 1),
    pos("recipient_64_bytes", 3, "a" * 64, 10, 5, 99),
    pos("recipient_1_byte", 3, "z", 10, 5, 99),
    pos("recipient_all_charset", 12, "ab-c_d.e0-9.testnet", 123456789012345678901234567890, 8, 1_800_000_000_000),
    pos("amount_2_pow_64", 1, "shop.testnet", 2**64, 2, 3),
    pos("amount_one", 9, "bob.near", 1, 0, 1),
    pos("endianness_probe", 0x0102030405060708, "x.near", 0x0102030405060708090A0B0C0D0E0F10, 0x1112131415161718, 0x2122232425262728),
]

negative = [
    neg("mandate_id_u64_overflow", "RangeError", mandateId=str(U64 + 1)),
    neg("mandate_id_negative", "RangeError", mandateId="-1"),
    neg("nonce_u64_overflow", "RangeError", nonce=str(U64 + 1)),
    neg("expires_u64_overflow", "RangeError", expiresAtMs=str(U64 + 1)),
    neg("amount_u128_overflow", "RangeError", amount=str(U128 + 1)),
    neg("amount_leading_zero", "RangeError", amount="007"),
    neg("amount_negative_sign", "RangeError", amount="-5"),
    neg("amount_plus_sign", "RangeError", amount="+5"),
    neg("amount_decimal_point", "RangeError", amount="1.5"),
    neg("amount_empty", "RangeError", amount=""),
    neg("amount_whitespace", "RangeError", amount=" 5"),
    neg("recipient_empty", "RangeError", recipient=""),
    neg("recipient_65_bytes", "RangeError", recipient="a" * 65),
    neg("recipient_uppercase", "RangeError", recipient="Shop.testnet"),
    neg("recipient_non_ascii", "RangeError", recipient="tökö.testnet"),
    neg("recipient_space", "RangeError", recipient="shop testnet"),
    neg("recipient_slash", "RangeError", recipient="shop/testnet"),
]

out = {
    "description": "Intent hash vectors for PRD 3.4; generated by tools/gen_vectors.py (independent of JS). Numeric inputs are decimal strings.",
    "positive": positive,
    "negative": negative,
}
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "vectors", "intent_hash.json")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w") as f:
    json.dump(out, f, indent=2, ensure_ascii=True)
    f.write("\n")
print(f"wrote {len(positive)} positive, {len(negative)} negative -> {os.path.normpath(path)}")
